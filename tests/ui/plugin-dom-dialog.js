import assert from "node:assert/strict";
import { withComponentFixture } from "./helpers/component-fixture.js";
import { poll } from "./helpers/native-app.js";
await withComponentFixture("plugin-dom-dialog",async(page,output)=>{
  const checks=[];
  const show=(/** @type {string} */ name,/** @type {any} */ options={})=>page.evaluate(({name,options})=>/** @type {any} */(window).__pluginDomDialog.show(name,options),{name,options});
  const snapshot=(/** @type {string} */ name)=>page.evaluate(name=>/** @type {any} */(window).__pluginDomDialog.snapshot(name),name);
  const dialog=(/** @type {string} */ name)=>page.getByRole("dialog",{name,exact:true});
  assert.equal((await show("alpha",{tall:true,wide:true})).returnsVoid,true);
  await dialog("alpha").waitFor();
  assert.equal((await snapshot("alpha")).sameNode,true);
  await page.getByRole("button",{name:"Owned DOM event",exact:true}).click();
  await page.getByRole("textbox",{name:"Owned DOM text",exact:true}).fill("ไทย😀");
  assert.equal((await snapshot("alpha")).clicks,1);assert.equal((await snapshot("alpha")).inputs,1);
  await page.evaluate(()=>/** @type {any} */(window).__pluginDomDialog.mutate("alpha"));
  await page.getByText("Owned live mutation",{exact:true}).waitFor();
  checks.push("Actual Svelte dialog mounts original HTMLElement and retains event listeners/live mutations/void return");
  assert.match(await dialog("alpha").getAttribute("class")||"",/plugin-dialog-tall/);
  await show("beta",{skinny:true});await dialog("beta").waitFor();
  assert.equal((await snapshot("alpha")).hides,1);assert.equal((await snapshot("alpha")).connected,false);
  const betaId=(await snapshot("beta")).id;
  assert.equal(await page.evaluate(id=>/** @type {any} */(window).__pluginDomDialog.close(id),betaId-1),false);
  assert.equal((await snapshot("beta")).connected,true);
  const invalid=await page.evaluate(()=>/** @type {any} */(window).__pluginDomDialog.invalid("beta"));
  assert.equal(invalid.length,3);assert.ok(invalid.every((/** @type {string} */ message)=>message!=="leaked"));
  checks.push("Singleton replacement detaches old body/onHide once, stale close and malformed inputs preserve current dialog");
  await page.getByRole("button",{name:"Close plugin dialog",exact:true}).click();await dialog("beta").waitFor({state:"detached"});
  assert.equal((await snapshot("beta")).hides,1);
  await show("abort");await dialog("abort").waitFor();
  await page.evaluate(()=>/** @type {any} */(window).__pluginDomDialog.abort("abort"));await dialog("abort").waitFor({state:"detached"});
  assert.equal((await snapshot("abort")).hides,1);
  checks.push("Explicit Close and owner Abort detach body before exactly one onHide callback");
  await show("owner-loss");await dialog("owner-loss").waitFor();
  await page.evaluate(()=>/** @type {any} */(window).__pluginDomDialog.ownerLoss("owner-loss"));await dialog("owner-loss").waitFor({state:"detached"});
  assert.equal((await snapshot("owner-loss")).hides,1);
  checks.push("Actual owner-current loss removes owned dialog and its callback lease");
  await show("before-reentrant",{reenter:true});await dialog("before-reentrant").waitFor();
  await show("superseded");await dialog("reentrant").waitFor();assert.equal(await dialog("superseded").count(),0);
  checks.push("onHide reentrant open wins over earlier replacement without destroying newer body");
  await show("reuse");await dialog("reuse").waitFor();
  await page.evaluate(()=>/** @type {any} */(window).__pluginDomDialog.reuse("reuse"));await dialog("reused").waitFor();
  assert.equal((await snapshot("reuse")).sameNode,true);assert.equal((await snapshot("reuse")).connected,true);
  checks.push("Reusing same original DOM node survives stale Svelte slot cleanup");
  await show("throw-hide",{throwOnHide:true});await dialog("throw-hide").waitFor();
  await show("after-error");await dialog("after-error").waitFor();
  assert.deepEqual(await page.evaluate(()=>/** @type {any} */(window).__pluginDomDialog.errors),["Error: owned onHide failure"]);
  checks.push("Throwing onHide is reported after cleanup and does not strand replacement dialog");
  await show("mount-error",{mountFailure:true});
  await poll(async()=>(await snapshot("mount-error")).hides===1,"Mount failure releases owner");
  assert.equal((await snapshot("mount-error")).connected,false);
  assert.equal(await dialog("mount-error").count(),0);
  assert.deepEqual(await page.evaluate(()=>/** @type {any} */(window).__pluginDomDialog.errors),["Error: owned onHide failure","Error: owned mount owner failure"]);
  await show("after-error");await dialog("after-error").waitFor();
  checks.push("Throwing owner check during mount releases body/callback and reports failure before recovery");
  const preview=await page.evaluate(()=>/** @type {any} */(window).__pluginDomDialog.show("preview",{},"preview"));assert.equal(preview.returnsVoid,true);
  assert.equal(await dialog("preview").count(),0);assert.equal((await snapshot("after-error")).connected,true);
  checks.push("Preview is void/no UI and does not replace active send dialog");
  await page.evaluate(()=>/** @type {any} */(window).__pluginDomDialog.destroy());
  await poll(async()=>(await snapshot("after-error")).hides===1,"Unmount releases original body and owner");
  assert.equal((await snapshot("after-error")).connected,false);
  const events=await page.evaluate(()=>/** @type {any} */(window).__pluginDomDialog.events);
  assert.ok(events.every((/** @type {any} */ event)=>event.detached));
  checks.push("Real host unmount releases body; every onHide observes detached DOM");
  await Bun.write(output+"/result.json",JSON.stringify({status:"passed",headless:true,checks,events,
    limits:"Actual browser DOM/Svelte host lifecycle, controlled host owner only; guest DOM/VM events/onHide/private bridge and native activation remain required."},null,2));
});
