// Generate static browser validators using Ajv's documented standalone API.
// Schemas: @scalar/openapi-validator (MIT), sourced from OpenAPI Initiative specifications.
import Ajv04 from "ajv-draft-04";
import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";

const root = new URL("../", import.meta.url);
const packageEntry = import.meta.resolve("@scalar/openapi-validator");
for (const version of ["2.0", "3.0", "3.1", "3.2"]) {
  const { default: schema } = await import(
    new URL(`./schemas/v${version}/schema.js`, packageEntry).href
  );
  const Engine = version === "2.0" || version === "3.0" ? Ajv04 : Ajv2020;
  const ajv = new Engine({
    strict: false,
    discriminator: true,
    allErrors: true,
    code: { source: true },
  });
  addFormats(ajv);
  ajv.addFormat("media-range", true);
  const validate = ajv.compile(schema);
  const temporary = new URL(
    `artifacts/openapi-build/validator-${version}.cjs`,
    root,
  );
  await Bun.write(temporary, standaloneCode(ajv, validate));
  const build = await Bun.build({
    entrypoints: [
      decodeURIComponent(temporary.pathname).replace(/^\/([A-Za-z]:)/, "$1"),
    ],
    target: "browser",
    format: "esm",
    minify: true,
  });
  if (!build.success) throw new Error(build.logs.map(String).join("\n"));
  await Bun.write(
    new URL(`src/lib/generated/openapi-${version}.js`, root),
    `// @ts-nocheck\n// Generated by scripts/build-openapi-validators.mjs; do not edit. Ajv/Scalar/OpenAPI schemas (MIT).\n${await build.outputs[0].text()}`,
  );
  console.log(`Generated OpenAPI ${version} validator`);
}
