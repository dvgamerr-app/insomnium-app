import {resolve} from "node:path";
import { mkdir } from "node:fs/promises";
const bundle = await Bun.build({
  entrypoints: ["scripts/plugin-buffer-entry.js"],
  target: "browser",
  format: "iife",
  minify: true,
  plugins:[{name:"isolated-stream-dependencies",setup(build){
    build.onResolve({filter:/^process\/?$/},()=>({path:resolve(import.meta.dir,"plugin-stream-process.js")}));
    build.onResolve({filter:/^buffer$/},()=>({path:resolve(import.meta.dir,"../node_modules/buffer/index.js")}));
    build.onResolve({filter:/^abort-controller$/},()=>({path:resolve(import.meta.dir,"../node_modules/abort-controller/dist/abort-controller.js")}));
  }}],
});
if (!bundle.success) throw Error(bundle.logs.map(String).join("\n"));
await mkdir("src/lib/generated", { recursive: true });
const license = (
  await Promise.all(
    ["buffer", "base64-js", "ieee754", "readable-stream", "events", "string_decoder", "safe-buffer", "abort-controller", "event-target-shim"].map(
      async (name) =>
        `${name}\n${await Bun.file(`node_modules/${name}/LICENSE`).text()}`,
    ),
  )
).join("\n\n");
const source = await bundle.outputs[0].text();
await Bun.write(
  "src/lib/generated/plugin-buffer.js",
  `// Generated by bun scripts/build-plugin-buffer.mjs.\n// Isolated Buffer and readable-stream; bundled dependency licenses below.\n/*\n${license}\n*/\nexport const pluginBufferSource = ${JSON.stringify(source)};\n`,
);
console.log("Generated isolated plugin Buffer polyfill");
